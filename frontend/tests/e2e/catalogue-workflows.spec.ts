import {test,expect} from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import {mockCatalogue} from './catalogue-fixture'
test.beforeEach(async({page})=>mockCatalogue(page))
for(const width of [375,1440])test(`custom filters retain multiple selections and alignment at ${width}px`,async({page})=>{
  await page.setViewportSize({width,height:1000});await page.goto('/search?type=anime')
  const format=page.getByRole('button',{name:'Format',exact:true})
  await format.click()
  await page.getByRole('menuitemcheckbox',{name:'TV',exact:true}).click()
  await page.getByRole('menuitemcheckbox',{name:'Movie',exact:true}).click()
  await expect(page.getByRole('menuitemcheckbox',{name:'TV',exact:true})).toHaveAttribute('aria-checked','true')
  await expect(page.getByRole('menuitemcheckbox',{name:'Movie',exact:true})).toHaveAttribute('aria-checked','true')
  expect(new URL(page.url()).searchParams.getAll('format')).toEqual(['TV','Movie'])
  await page.keyboard.press('Escape');await expect(format).toBeFocused()
  await format.press('Enter');await page.getByRole('menuitem',{name:'Clear selection'}).click()
  expect(new URL(page.url()).searchParams.getAll('format')).toEqual([])
  await page.keyboard.press('Escape')
  const controls=await page.locator('.select-trigger').evaluateAll(nodes=>nodes.map(node=>node.getBoundingClientRect().height))
  expect(controls).toHaveLength(6);expect(Math.max(...controls)-Math.min(...controls)).toBeLessThan(1)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await format.click()
  const issues=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()
  expect(issues.violations.map(issue=>({id:issue.id,nodes:issue.nodes.map(node=>({target:node.target,summary:node.failureSummary}))}))).toEqual([])
  await page.screenshot({path:test.info().outputPath('custom-filters.png'),fullPage:true})
})
for(const type of ['anime','manga'])for(const width of [375,1440])test(`${type} browse shelves scroll and open matching full results at ${width}px`,async({page})=>{
  await page.setViewportSize({width,height:1000});await page.goto(`/${type}`)
  await expect(page.locator('.browse-shelf')).toHaveCount(5)
  await expect(page.getByRole('navigation',{name:'Pagination'})).toHaveCount(0)
  const rail=page.getByRole('region',{name:'Most popular',exact:true})
  expect(await rail.evaluate(node=>node.scrollWidth>node.clientWidth)).toBe(true)
  const rows=await rail.locator('.media-card').evaluateAll(nodes=>nodes.map(node=>Math.round(node.getBoundingClientRect().top)))
  expect(new Set(rows).size).toBe(1)
  await rail.focus();await page.keyboard.press('ArrowRight')
  await expect.poll(()=>rail.evaluate(node=>node.scrollLeft)).toBeGreaterThan(0)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  const issues=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()
  expect(issues.violations.map(issue=>issue.id)).toEqual([])
  await page.locator('.site-header .wordmark').focus();await page.evaluate(()=>window.scrollTo(0,0))
  await page.screenshot({path:test.info().outputPath(`${type}-browse.png`),fullPage:true})
  await page.locator('.browse-shelf').filter({has:page.getByRole('heading',{name:'Top rated',exact:true})}).getByRole('link',{name:'View all'}).click()
  expect(new URL(page.url()).pathname).toBe('/search')
  expect(new URL(page.url()).searchParams.get('type')).toBe(type)
  expect(new URL(page.url()).searchParams.get('sort')).toBe('score')
  await expect(page.locator('.select-trigger')).toHaveCount(6)
  await expect(page.locator('.browse-shelf')).toHaveCount(0)
  await expect(page.locator('.card-title')).toHaveCount(type==='anime'?12:6)
})
for(const width of [375,1440])test(`account menu provides keyboard navigation and completion links at ${width}px`,async({page})=>{
  await page.setViewportSize({width,height:900});await page.goto('/tests/e2e/account-menu-preview.html')
  const trigger=page.getByRole('button',{name:'Account menu',exact:true})
  const bounds=await trigger.boundingBox();expect(bounds!.width).toBe(bounds!.height)
  await trigger.focus();await page.keyboard.press('Enter')
  const menu=page.getByRole('menu',{name:'Account menu',exact:true})
  for(const label of ['Dashboard','Profile','Settings','My library','Wishlist','Completed','Collections','Watch and reading history','Your statistics','Sign out'])await expect(menu.getByRole('menuitem',{name:label,exact:true})).toBeVisible()
  await page.keyboard.press('Escape');await expect(trigger).toBeFocused()
  await trigger.click();await page.getByRole('heading',{name:'Account navigation fixture'}).click({position:{x:5,y:5}});await expect(menu).toHaveCount(0)
  await trigger.click()
  const issues=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()
  expect(issues.violations.map(issue=>issue.id)).toEqual([])
  await page.screenshot({path:test.info().outputPath('account-menu.png')})
  await menu.getByRole('menuitem',{name:'Completed',exact:true}).click()
  await expect(page.getByTestId('route')).toHaveText('/library?status=completed')
  await expect(menu).toHaveCount(0)
  await trigger.click();await menu.getByRole('menuitem',{name:'Sign out',exact:true}).click()
  await expect(page.getByRole('status')).toHaveText('Sign out requested')
})
