import { act, cleanup, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, expect, it, vi } from 'vitest'
import { SearchField } from './search-field'

afterEach(()=>{cleanup();vi.useRealTimers()})
it('waits 300 ms after the latest edit and preserves the same focused input',async()=>{
  vi.useFakeTimers()
  const commit=vi.fn()
  const view=render(<SearchField value="One Pice" onCommit={commit}/>)
  const input=screen.getByRole('searchbox')
  input.focus()
  fireEvent.change(input,{target:{value:'One Piece'}})
  await act(async()=>{await vi.advanceTimersByTimeAsync(299)})
  expect(commit).not.toHaveBeenCalled()
  await act(async()=>{await vi.advanceTimersByTimeAsync(1)})
  expect(commit).toHaveBeenCalledExactlyOnceWith('One Piece')
  view.rerender(<SearchField value="One Piece" onCommit={commit}/>)
  expect(screen.getByRole('searchbox')).toBe(input)
  expect(input).toHaveFocus()
})
it('supports clear, immediate submit and composition without premature searches',async()=>{
  vi.useFakeTimers()
  const commit=vi.fn()
  render(<SearchField value="One Piece" onCommit={commit}/>)
  const input=screen.getByRole('searchbox')
  fireEvent.compositionStart(input)
  fireEvent.change(input,{target:{value:'ワンピース'}})
  await act(async()=>{await vi.advanceTimersByTimeAsync(500)})
  expect(commit).not.toHaveBeenCalled()
  fireEvent.compositionEnd(input)
  fireEvent.submit(screen.getByRole('search'))
  expect(commit).toHaveBeenLastCalledWith('ワンピース')
  fireEvent.click(screen.getByRole('button',{name:'Clear search'}))
  expect(commit).toHaveBeenLastCalledWith('')
  expect(input).toHaveValue('')
  expect(input).toHaveFocus()
  await act(async()=>{await vi.advanceTimersByTimeAsync(500)})
  expect(commit).toHaveBeenCalledTimes(2)
})
